import { afterEach, describe, expect, test, vi } from "vitest";
import { pathToFileURL } from "url";
import { Parser } from "n3";
import type { Quad, Term } from "@rdfjs/types";
import { LDES, PROV, RDF, SDS, TREE } from "@treecg/types";
import { createRunner, channel } from "@rdfc/js-runner/lib/testUtils";
import { createLogger, transports } from "winston";
import type { FullProc } from "@rdfc/js-runner";
import { DataFactory } from "rdf-data-factory";
import { Pipeline } from "../lib/pipeline";
import { LdesDiskWriter } from "../lib/ldesDiskWriter";

vi.mock("node:fs", async () => {
    const { fs } = await import("memfs");
    return { default: fs, ...(fs as object) };
});

const df = new DataFactory();
const S = "http://mystream/";
const RDFC = "https://w3id.org/rdf-connect#";

// The real file system, for the processor configurations; the writer gets memfs.
const { readFileSync } =
    await vi.importActual<typeof import("node:fs")>("node:fs");

function config(file: string): Quad[] {
    const path = process.cwd() + "/configs/" + file;
    return new Parser({ baseIRI: pathToFileURL(path).href }).parse(
        readFileSync(path, "utf8"),
    );
}

// Sdsify -> fan-out -> two bucketizers -> merge -> LDES writer, with the
// channels and processors named under one prefix, as a deployment would.
const PIPELINE = `
@prefix rdfc: <https://w3id.org/rdf-connect#>.
@prefix tree: <https://w3id.org/tree#>.
@prefix sh: <http://www.w3.org/ns/shacl#>.
@prefix dcat: <http://www.w3.org/ns/dcat#>.
@prefix ex: <http://example.org/>.
@prefix stream: <${S}>.

# Stand-ins for processors of other packages, which only forward records.
[] a sh:NodeShape; sh:targetClass ex:FanOut;
  sh:property [ sh:path rdfc:reader; sh:class rdfc:Reader ], [ sh:path rdfc:writer; sh:class rdfc:Writer ].
[] a sh:NodeShape; sh:targetClass ex:Converge;
  sh:property [ sh:path rdfc:reader; sh:class rdfc:Reader ], [ sh:path rdfc:writer; sh:class rdfc:Writer ].

stream:raw a rdfc:Reader, rdfc:Writer.
stream:observations a rdfc:Reader, rdfc:Writer.
stream:obs-1 a rdfc:Reader, rdfc:Writer.
stream:obs-2 a rdfc:Reader, rdfc:Writer.
stream:by-time a rdfc:Reader, rdfc:Writer.
stream:by-subject a rdfc:Reader, rdfc:Writer.
stream:views a rdfc:Reader, rdfc:Writer.

stream:dataset a dcat:Dataset; dcat:title "Observations".

stream:sdsify a rdfc:Sdsify;
  rdfc:input stream:raw;
  rdfc:output stream:observations;
  rdfc:metadataConfig [
    rdfc:description "Observations of the sensors";
    rdfc:timestampPath ex:time;
    rdfc:dataset stream:dataset;
  ];
  rdfc:shape """
    @prefix sh: <http://www.w3.org/ns/shacl#>.
    @prefix ex: <http://example.org/>.
    ex:Shape a sh:NodeShape; sh:targetClass ex:Observation; sh:property [ sh:path ex:time ].
  """.

stream:fan-out a ex:FanOut; rdfc:reader stream:observations; rdfc:writer stream:obs-1, stream:obs-2.

stream:bucketize-time a rdfc:Bucketize;
  rdfc:channels [ rdfc:dataInput stream:obs-1; rdfc:dataOutput stream:by-time ];
  rdfc:bucketizeStrategy ( stream:subject stream:page ).
stream:bucketize-subject a rdfc:Bucketize;
  rdfc:channels [ rdfc:dataInput stream:obs-2; rdfc:dataOutput stream:by-subject ];
  rdfc:bucketizeStrategy stream:subject.

stream:subject a tree:SubjectFragmentation; tree:fragmentationPath ex:sensor.
stream:page a tree:PageFragmentation; tree:pageSize 10.

stream:merge a ex:Converge; rdfc:reader ( stream:by-time stream:by-subject ); rdfc:writer stream:views.

stream:writer a rdfc:LdesDiskWriter; rdfc:dataInput stream:views; rdfc:directory "/ldes/".
`;

function pipelineQuads(): Quad[] {
    return [
        ...config("sdsify.ttl"),
        ...config("bucketizer.ttl"),
        ...config("ldes_disk_writer.ttl"),
        ...new Parser().parse(PIPELINE),
    ];
}

const values = (terms: Term[]) => terms.map((t) => t.value);
const objects = (quads: Quad[], s: string | Term, p: Term) =>
    quads
        .filter(
            (q) =>
                (typeof s === "string"
                    ? q.subject.value === s
                    : q.subject.equals(s)) && q.predicate.equals(p),
        )
        .map((q) => q.object);

describe("Streams from the pipeline description", () => {
    test("a stream is the channel where it starts, found through forwarding processors", () => {
        const pipeline = new Pipeline(pipelineQuads());
        expect(values(pipeline.streamsOn(S + "views"))).toEqual([
            S + "by-time",
            S + "by-subject",
        ]);
        expect(values(pipeline.streamsOn(S + "obs-2"))).toEqual([
            S + "observations",
        ]);
        expect(pipeline.streamsOn(S + "raw")).toEqual([]);
    });

    test("a bucketized stream is generated by its processor, from the stream it read", () => {
        const pipeline = new Pipeline(pipelineQuads());
        const quads = pipeline.describe(pipeline.streamsOn(S + "views")[0]);

        expect(
            values(objects(quads, S + "by-time", PROV.terms.wasGeneratedBy)),
        ).toEqual([S + "bucketize-time"]);
        const activity = S + "bucketize-time";
        expect(values(objects(quads, activity, RDF.terms.type))).toContain(
            LDES.terms.Bucketization.value,
        );
        expect(values(objects(quads, activity, PROV.terms.used))).toEqual([
            S + "observations",
            S + "subject",
            S + "page",
        ]);

        // The strategies are published as configured, outermost first.
        const list = objects(
            quads,
            activity,
            df.namedNode(RDFC + "bucketizeStrategy"),
        )[0];
        const first = objects(quads, list, df.namedNode(RDF.first));
        expect(values(first)).toEqual([S + "subject"]);
        expect(
            values(objects(quads, S + "page", TREE.terms.custom("pageSize"))),
        ).toEqual(["10"]);

        // No stream is derived from itself.
        expect(
            quads.some(
                (q) =>
                    q.predicate.equals(PROV.terms.used) &&
                    objects(quads, q.object, PROV.terms.wasGeneratedBy).some(
                        (a) => a.equals(q.subject),
                    ),
            ),
        ).toBe(false);
    });

    test("a derived stream carries the members and dataset of its source", () => {
        const pipeline = new Pipeline(pipelineQuads());
        const quads = pipeline.describe(pipeline.streamsOn(S + "views")[1]);

        const carries = objects(quads, S + "by-subject", SDS.terms.carries);
        expect(carries).toEqual(
            objects(quads, S + "observations", SDS.terms.carries),
        );
        expect(values(objects(quads, carries[0], SDS.terms.shape))).toEqual([
            "http://example.org/Shape",
        ]);

        expect(
            values(objects(quads, S + "by-subject", SDS.terms.dataset)),
        ).toEqual([S + "dataset"]);
        expect(
            values(objects(quads, S + "dataset", LDES.terms.timestampPath)),
        ).toEqual(["http://example.org/time"]);
        expect(
            values(
                objects(
                    quads,
                    S + "dataset",
                    df.namedNode("http://www.w3.org/ns/dcat#title"),
                ),
            ),
        ).toEqual(["Observations"]);
        expect(
            values(
                objects(quads, S + "observations", PROV.terms.wasGeneratedBy),
            ),
        ).toEqual([S + "sdsify"]);
    });
});

describe("LdesDiskWriter publishes the streams the pipeline sends it", () => {
    afterEach(async () => {
        const { vol } = await import("memfs");
        vol.reset();
    });

    test("one view per stream, with its derivation, before any data", async () => {
        const { fs } = await import("memfs");
        const runner = createRunner();
        const [writer, reader] = channel(runner, S + "views");
        const proc = <FullProc<LdesDiskWriter>>new LdesDiskWriter(
            {
                data: reader,
                directory: "/ldes/",
                nameMap: [
                    { stream: df.namedNode(S + "by-time"), name: "by-time" },
                ],
                pipeline: pipelineQuads(),
            },
            createLogger({
                transports: [new transports.Console({ level: "warn" })],
            }),
        );
        await proc.init();
        const done = proc.transform();
        await writer.close();
        await done;

        const root = new Parser({
            baseIRI: "http://localhost/index.trig",
        }).parse(fs.readFileSync("/ldes/index.trig").toString());
        const views = objects(
            root,
            "http://localhost/index.trig",
            TREE.terms.view,
        );
        expect(values(views).sort()).toEqual([
            "http://localhost/by-time/index.trig",
            "http://localhost/http_3A_2F_2Fmystream_2Fby-subject/index.trig",
        ]);
        const managedBy = root
            .filter((q) => q.predicate.equals(LDES.terms.custom("managedBy")))
            .map((q) => q.object.value)
            .sort();
        expect(managedBy).toEqual([S + "by-subject", S + "by-time"]);
        expect(
            values(
                objects(root, "http://localhost/index.trig", TREE.terms.shape),
            ),
        ).toEqual(["http://example.org/Shape"]);
        expect(
            values(
                objects(
                    root,
                    "http://localhost/index.trig",
                    LDES.terms.timestampPath,
                ),
            ),
        ).toEqual(["http://example.org/time"]);
        expect(
            values(objects(root, S + "by-time", PROV.terms.wasGeneratedBy)),
        ).toEqual([S + "bucketize-time"]);
    });
});
